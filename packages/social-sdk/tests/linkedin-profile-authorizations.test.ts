import { it } from "node:test";
import assert from "node:assert/strict";
import { connectedAccountRef } from "../src/index.js";
import { linkedin, type LinkedInOrganizationAuthorizationKey } from "../src/platforms/linkedin.js";
import { SocialError } from "../src/core/errors.js";

const nativeContext = {
  backendInstance: "default",
  correlationId: "test",
  retryBudget: { maxAttempts: 1, maxElapsedMs: 1000 },
};

const memberUrn = "urn:li:person:yrZCpj2Z12";

const member = connectedAccountRef({
  backend: "default",
  platform: "linkedin",
  accountId: memberUrn,
});

interface Call {
  readonly url: string;
  readonly headers: Headers;
}

const native = (author: string, respond: (call: Call) => Response) => {
  const calls: Call[] = [];

  const adapter = linkedin({
    auth: {
      accessToken: "secret",
      author: author === memberUrn ? memberUrn : "urn:li:organization:2414183",
    },
    apiVersion: "202610",
    fetch: async (input, init) => {
      const call = { url: String(input), headers: new Headers(init?.headers) };

      calls.push(call);

      return respond(call);
    },
  });

  return { calls, native: adapter.native! };
};

const bob = {
  firstName: { localized: { en_US: "Bob" }, preferredLocale: { country: "US", language: "en" } },
  localizedFirstName: "Bob",
  headline: { localized: { en_US: "API Enthusiast at LinkedIn" } },
  vanityName: "bsmith",
  id: "yrZCpj2Z12",
  lastName: { localized: { en_US: "Smith" } },
  profilePicture: { displayImage: "urn:li:digitalmediaAsset:C4D00AAAAbBCDEFGhiJ" },
  geoLocation: { geo: "urn:li:geo:12345", autoGenerated: false },
};

it("reads the member profile with GET /v2/me and a projection", async () => {
  const { calls, native: api } = native(memberUrn, () => Response.json(bob));

  const profile = await api.getProfile({
    account: member,
    projection: "(id,firstName,lastName,geoLocation(geo~,autoGenerated))",
    context: nativeContext,
  });

  assert.equal(
    calls[0]?.url,
    "https://api.linkedin.com/v2/me?projection=(id,firstName,lastName,geoLocation(geo~,autoGenerated))",
  );
  assert.equal(calls[0]?.headers.get("Linkedin-Version"), null);
  assert.equal(profile.personUrn, memberUrn);
  assert.equal(profile.firstName, "Bob");
  assert.equal(profile.lastName, "Smith");
  assert.equal(profile.headline, "API Enthusiast at LinkedIn");
  assert.equal(profile.vanityName, "bsmith");
  assert.equal(profile.profilePictureUrn, "urn:li:digitalmediaAsset:C4D00AAAAbBCDEFGhiJ");
  assert.deepEqual(profile.geoLocation, { geo: "urn:li:geo:12345", autoGenerated: false });

  await assert.rejects(
    api.getProfile({ account: member, projection: "(id,firstName", context: nativeContext }),
    (error: SocialError) => error.code === "invalid_input",
  );

  const other = native(memberUrn, () => Response.json({ ...bob, id: "someoneElse" }));

  await assert.rejects(
    other.native.getProfile({ account: member, context: nativeContext }),
    (error: SocialError) => error.code === "unauthorized",
  );
  assert.equal(calls.length, 1);
});

it("reads other members with /v2/people/(id:...) and batch /v2/people?ids=List(...)", async () => {
  const { calls, native: api } = native(memberUrn, (call) =>
    call.url.includes("ids=List")
      ? Response.json({
          results: {
            "(id:abc123)": { id: "abc123", localizedFirstName: "Ann", localizedLastName: "Lee" },
          },
          statuses: { "(id:missing9)": 404 },
          errors: {},
        })
      : Response.json({ id: "abc123", localizedFirstName: "Ann" }),
  );

  const single = await api.getPeople({
    account: member,
    people: ["urn:li:person:abc123"],
    context: nativeContext,
  });

  assert.equal(calls[0]?.url, "https://api.linkedin.com/v2/people/(id:abc123)");
  assert.equal(calls[0]?.headers.get("X-Restli-Protocol-Version"), "2.0.0");
  assert.equal(single.profiles[0]?.firstName, "Ann");

  const batch = await api.getPeople({
    account: member,
    people: ["urn:li:person:abc123", "urn:li:person:missing9"],
    projection: "(id,firstName,lastName)",
    context: nativeContext,
  });

  assert.equal(
    calls[1]?.url,
    "https://api.linkedin.com/v2/people?ids=List((id:abc123),(id:missing9))&projection=(id,firstName,lastName)",
  );
  assert.equal(calls[1]?.headers.get("X-Restli-Protocol-Version"), "2.0.0");
  assert.deepEqual(
    batch.profiles.map((profile) => [profile.personUrn, profile.firstName, profile.lastName]),
    [["urn:li:person:abc123", "Ann", "Lee"]],
  );
  assert.deepEqual(batch.errors, [{ id: "urn:li:person:missing9", status: 404 }]);

  const bare = native(memberUrn, () =>
    Response.json({ results: { abc123: { id: "abc123" }, def456: { id: "def456" } } }),
  );

  const keyed = await bare.native.getPeople({
    account: member,
    people: ["urn:li:person:abc123", "urn:li:person:def456"],
    context: nativeContext,
  });

  assert.deepEqual(
    keyed.profiles.map((profile) => profile.personUrn),
    ["urn:li:person:abc123", "urn:li:person:def456"],
  );

  await assert.rejects(
    api.getPeople({ account: member, people: [], context: nativeContext }),
    (error: SocialError) => error.code === "invalid_input",
  );
});

it("checks organization authorizations with get, batch get and the batch finder", async () => {
  const approved = {
    impersonator: memberUrn,
    action: { OrganizationContentAuthorizationActionType: { actionType: "ORGANIC_SHARE_CREATE" } },
    organization: "urn:li:organization:11111111",
    status: { "com.linkedin.organization.Approved": {} },
  };

  const denied = {
    impersonator: memberUrn,
    action: { OrganizationAnalyticsAuthorizationAction: { actionType: "UPDATE_ANALYTICS_READ" } },
    organization: "urn:li:organization:11111112",
    status: {
      "com.linkedin.organization.Denied": {
        reasons: ["ORGANIZATION_INACTIVE", "MEMBER_HAS_INSUFFICIENT_PERMISSIONS_IN_ACCESS_CONTROL"],
      },
    },
  };

  const { calls, native: api } = native(memberUrn, (call) => {
    if (call.url.includes("bq=authorizationActionsAndImpersonator"))
      return Response.json({
        elements: [
          { elements: [approved], paging: { count: 10, start: 0, links: [] } },
          { elements: [denied], paging: { count: 10, start: 0, links: [] } },
        ],
      });

    if (call.url.includes("ids=List"))
      return Response.json({
        statuses: {},
        results: {
          "(action:(OrganizationContentAuthorizationActionType:(actionType:ORGANIC_SHARE_CREATE)),impersonator:urn%3Ali%3Aperson%3AyrZCpj2Z12,organization:urn%3Ali%3Aorganization%3A11111111)":
            approved,
        },
        errors: {},
      });

    return Response.json(denied);
  });

  const single = await api.getOrganizationAuthorization({
    account: member,
    key: {
      impersonator: memberUrn,
      organization: "urn:li:organization:11111112",
      action: {
        group: "organizationAnalyticsAuthorizationAction",
        actionType: "UPDATE_ANALYTICS_READ",
      },
    },
    context: nativeContext,
  });

  assert.equal(
    calls[0]?.url,
    "https://api.linkedin.com/rest/organizationAuthorizations/(impersonator:urn%3Ali%3Aperson%3AyrZCpj2Z12,organization:urn%3Ali%3Aorganization%3A11111112,action:(organizationAnalyticsAuthorizationAction:(actionType:UPDATE_ANALYTICS_READ)))",
  );
  assert.equal(calls[0]?.headers.get("X-Restli-Protocol-Version"), "2.0.0");
  assert.deepEqual(single, {
    impersonator: memberUrn,
    organization: "urn:li:organization:11111112",
    actionType: "UPDATE_ANALYTICS_READ",
    approved: false,
    status: "Denied",
    reasons: ["ORGANIZATION_INACTIVE", "MEMBER_HAS_INSUFFICIENT_PERMISSIONS_IN_ACCESS_CONTROL"],
  });

  const shareKey: LinkedInOrganizationAuthorizationKey = {
    impersonator: memberUrn,
    organization: "urn:li:organization:11111111",
    action: { group: "organizationContentAuthorizationAction", actionType: "ORGANIC_SHARE_CREATE" },
  };

  const roleKey: LinkedInOrganizationAuthorizationKey = {
    impersonator: memberUrn,
    organization: "urn:li:organization:11111111",
    action: { group: "organizationRoleAuthorizationAction", actionType: "ADMINISTRATOR_READ" },
  };

  const batch = await api.getOrganizationAuthorizations({
    account: member,
    keys: [shareKey, roleKey],
    context: nativeContext,
  });

  assert.equal(
    calls[1]?.url,
    "https://api.linkedin.com/rest/organizationAuthorizations?ids=List((impersonator:urn%3Ali%3Aperson%3AyrZCpj2Z12,organization:urn%3Ali%3Aorganization%3A11111111,action:(organizationContentAuthorizationAction:(actionType:ORGANIC_SHARE_CREATE))),(impersonator:urn%3Ali%3Aperson%3AyrZCpj2Z12,organization:urn%3Ali%3Aorganization%3A11111111,action:(organizationRoleAuthorizationAction:(actionType:ADMINISTRATOR_READ))))",
  );
  assert.deepEqual(
    batch.authorizations.map((entry) => [entry.actionType, entry.approved]),
    [["ORGANIC_SHARE_CREATE", true]],
  );
  assert.deepEqual(batch.missing, [roleKey]);

  const found = await api.findOrganizationAuthorizations({
    account: member,
    actions: [
      { group: "organizationContentAuthorizationAction", actionType: "ORGANIC_SHARE_CREATE" },
      { group: "organizationAnalyticsAuthorizationAction", actionType: "UPDATE_ANALYTICS_READ" },
    ],
    context: nativeContext,
  });

  assert.equal(
    calls[2]?.url,
    "https://api.linkedin.com/rest/organizationAuthorizations?bq=authorizationActionsAndImpersonator&authorizationActions=List((authorizationAction:(organizationContentAuthorizationAction:(actionType:ORGANIC_SHARE_CREATE))),(authorizationAction:(organizationAnalyticsAuthorizationAction:(actionType:UPDATE_ANALYTICS_READ))))",
  );
  assert.deepEqual(
    found.map((group) => group.map((entry) => [entry.organization, entry.status])),
    [[["urn:li:organization:11111111", "Approved"]], [["urn:li:organization:11111112", "Denied"]]],
  );

  await assert.rejects(
    api.getOrganizationAuthorization({
      account: member,
      key: {
        ...shareKey,
        action: {
          group: "organizationProfileAuthorizationAction",
          actionType: "ADMINISTRATION_PAGE_VIEW",
        },
        organization: "urn:li:organization:abc",
      },
      context: nativeContext,
    }),
    (error: SocialError) => error.code === "invalid_input",
  );
  assert.equal(calls.length, 3);
});

it("reads organization video analytics with GET /rest/videoAnalytics?q=entity", async () => {
  const organization = connectedAccountRef({
    backend: "default",
    platform: "linkedin",
    accountId: "urn:li:organization:2414183",
  });

  const { calls, native: api } = native("urn:li:organization:2414183", () =>
    Response.json({
      elements: [
        {
          entity: "urn:li:ugcPost:6426130460119830528",
          statisticsType: "TIME_WATCHED_FOR_VIDEO_VIEWS",
          timeRange: { end: 1535500800000, start: 1535414400000 },
          value: 5400,
        },
      ],
      paging: { count: 1, links: [], start: 0, total: 3 },
    }),
  );

  const page = await api.getOrganizationVideoAnalytics({
    account: organization,
    postId: "urn:li:ugcPost:6426130460119830528",
    metric: "TIME_WATCHED_FOR_VIDEO_VIEWS",
    aggregation: "DAY",
    timeRange: { start: 1531165717442, end: 1531770742335 },
    limit: 1,
    context: nativeContext,
  });

  assert.equal(
    calls[0]?.url,
    "https://api.linkedin.com/rest/videoAnalytics?q=entity&entity=urn%3Ali%3AugcPost%3A6426130460119830528&type=TIME_WATCHED_FOR_VIDEO_VIEWS&timeRange=(start:1531165717442,end:1531770742335)&aggregation=DAY&start=0&count=1",
  );
  assert.equal(calls[0]?.headers.get("X-Restli-Protocol-Version"), "2.0.0");
  assert.deepEqual(page, {
    items: [
      {
        metric: "TIME_WATCHED_FOR_VIDEO_VIEWS",
        value: 5400,
        timeRange: { start: 1535414400000, end: 1535500800000 },
      },
    ],
    nextCursor: "1",
  });

  await assert.rejects(
    api.getOrganizationVideoAnalytics({
      account: organization,
      postId: "urn:li:share:1",
      metric: "VIEWER",
      context: nativeContext,
    }),
    (error: SocialError) => error.code === "invalid_input",
  );
  await assert.rejects(
    api.getOrganizationVideoAnalytics({
      account: organization,
      postId: "urn:li:ugcPost:1",
      metric: "VIEWER",
      timeRange: { start: 10, end: 5 },
      context: nativeContext,
    }),
    (error: SocialError) => error.code === "invalid_input",
  );
  assert.equal(calls.length, 1);

  const memberApi = native(memberUrn, () => Response.json({}));

  await assert.rejects(
    memberApi.native.getOrganizationVideoAnalytics({
      account: member,
      postId: "urn:li:ugcPost:1",
      metric: "VIEWER",
      context: nativeContext,
    }),
    (error: SocialError) => error.code === "unsupported_capability",
  );
});
