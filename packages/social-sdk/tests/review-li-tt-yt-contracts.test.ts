import assert from "node:assert/strict";
import { it } from "node:test";
import { connectedAccountRef } from "../src/index.js";
import { linkedin } from "../src/platforms/linkedin.js";
import { youtube } from "../src/platforms/youtube.js";
import { createTikTokQrCode } from "../src/server/oauth.js";

const context = {
  backendInstance: "default",
  correlationId: "review-li-tt-yt",
  retryBudget: { maxAttempts: 1, maxElapsedMs: 5000 },
};

it("TikTok QR creation accepts the documented aweme scan URL", async () => {
  // https://developers.tiktok.com/doc/login-kit-qr-code-authorization, Get QR Code success.
  const fetch = async () =>
    Response.json({
      scan_qrcode_url:
        "aweme://authorize?authType=100&client_key=review-client&client_ticket=tobefilled",
      token: "review-qr-token",
    });

  const qr = await createTikTokQrCode(
    { clientId: "review-client", fetch },
    { clientTicket: "review-ticket" },
  );

  assert.equal(
    qr.scanQrCodeUrl,
    "aweme://authorize?authType=100&client_key=review-client&client_ticket=review-ticket",
  );
  assert.equal(qr.token, "review-qr-token");
});

it("LinkedIn getProfile accepts the documented geoLocation-only projection response", async () => {
  // https://learn.microsoft.com/en-us/linkedin/shared/integrations/people/profile-api,
  // Location Display Name explicitly projects only geoLocation, without id.
  const fields = {
    geoLocation: {
      geo: "urn:li:geo:12345",
      autoGenerated: false,
      "geo~": {
        id: 12345,
        defaultLocalizedName: {
          locale: { country: "US", language: "en" },
          value: "San Francisco Bay Area",
        },
      },
    },
  };

  const account = connectedAccountRef({
    backend: "default",
    platform: "linkedin",
    accountId: "urn:li:person:review-member",
  });

  const fetch = async (input: string | URL | Request) => {
    const projection = new URL(String(input)).searchParams.get("projection") ?? "";

    return Response.json(
      /(?:\(|,)id(?:,|\))/.test(projection) ? { id: "review-member", ...fields } : fields,
    );
  };

  const adapter = linkedin({
    auth: { accessToken: "review-token", author: "urn:li:person:review-member" },
    apiVersion: "202610",
    fetch,
  });

  assert.ok(adapter.native);

  const profile = await adapter.native.getProfile({
    account,
    projection: "(geoLocation(geo~,autoGenerated))",
    context,
  });

  assert.deepEqual(profile.geoLocation, { geo: "urn:li:geo:12345", autoGenerated: false });
  assert.equal(profile.personUrn, account.accountId);
});

it("YouTube live chat stream classifies documented HTTP 403 rateLimitExceeded as rate_limited", async () => {
  // https://developers.google.com/youtube/v3/live/docs/liveChatMessages/streamList,
  // Errors, When using web traffic to connect: HTTP 403 rateLimitExceeded.
  const fetch = async () =>
    Response.json(
      {
        error: {
          code: 403,
          message: "Requests are being sent too frequently.",
          errors: [{ domain: "youtube.liveChat", reason: "rateLimitExceeded" }],
        },
      },
      { status: 403, headers: { "retry-after": "5" } },
    );

  const adapter = youtube({
    auth: { accessToken: "review-token", channelId: "review-channel" },
    fetch,
  });

  assert.ok(adapter.native);

  const stream = adapter.native.liveChatStream({ liveChatId: "review-chat", context });

  await assert.rejects(stream.next(), { code: "rate_limited" });
});
